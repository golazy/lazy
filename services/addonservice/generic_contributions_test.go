func TestLocalManifestInstallsReversesAndProtectsDeclarativeContributions(t *testing.T) {
	dir := fixtureApp(t, "v0.1.21")
	writeFile(t, dir, "package.json", "{\n  \"dependencies\": {\n    \"kept\": \"4.5.6\"\n  },\n  \"private\": true\n}\n")
	writeFile(t, dir, "js.toml", "[entrypoint.turbo]\nmodule = \"@hotwired/turbo\"\n")
	writeFile(t, dir, "plugin/lazyaddon.toml", genericManifest("seo"))
	controllerSource := "package controllers\n\nfunc SEOEnabled() bool { return true }\n"
	writeFile(t, dir, "plugin/files/controller.go", controllerSource)
	writeFile(t, dir, "plugin/files/custom.go", "// Code generated by publisher. DO NOT EDIT.\n\npackage controllers\n")
	writeFile(t, dir, "plugin/files/check", "#!/usr/bin/env bash\nset -euo pipefail\necho checked\n")
	if err := os.Chmod(filepath.Join(dir, "plugin/files/check"), 0o755); err != nil {
		t.Fatal(err)
	}

	manager := addonservice.Manager{Dir: dir, ManifestPaths: []string{"plugin/lazyaddon.toml"}}
	install, err := manager.Add("seo")
	if err != nil {
		t.Fatal(err)
	}
	if err := install.Apply(); err != nil {
		t.Fatal(err)
	}

	controller := readFile(t, dir, "app/controllers/seo_addon.go")
	if !strings.HasPrefix(controller, "// Code generated by lazy add-ons. DO NOT EDIT.\n\npackage controllers") {
		t.Fatalf("generated controller =\n%s", controller)
	}
	custom := readFile(t, dir, "app/controllers/custom_addon.go")
	if !strings.HasPrefix(custom, "// Code generated by publisher. DO NOT EDIT.") || strings.Contains(custom, "generated by lazy add-ons") {
		t.Fatalf("publisher generated header was not preserved:\n%s", custom)
	}
	taskInfo, err := os.Stat(filepath.Join(dir, ".mise/tasks/seo/check"))
	if err != nil {
		t.Fatal(err)
	}
	if taskInfo.Mode().Perm() != 0o755 {
		t.Fatalf("task mode = %o, want 755", taskInfo.Mode().Perm())
	}
	packageJSON := readFile(t, dir, "package.json")
	if !strings.Contains(packageJSON, `"@scope/seo": "1.2.3"`) || !strings.Contains(packageJSON, `"kept": "4.5.6"`) {
		t.Fatalf("package.json contributions =\n%s", packageJSON)
	}
	jsManifest := readFile(t, dir, "js.toml")
	if !strings.Contains(jsManifest, "[entrypoint.seo]") || !strings.Contains(jsManifest, `module = "@scope/seo/entry"`) || !strings.Contains(jsManifest, "[entrypoint.turbo]") {
		t.Fatalf("js.toml contributions =\n%s", jsManifest)
	}
	state, err := addonservice.ReadState(dir)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(state.Addons[0].ManifestDigest, "sha256:") || strings.HasPrefix(state.Addons[0].ManifestDigest, "builtin:") {
		t.Fatalf("artifact digest = %q", state.Addons[0].ManifestDigest)
	}
	if got := state.Addons[0].Build.Tasks; len(got) != 1 || got[0] != "seo:check" {
		t.Fatalf("locked tasks = %#v", got)
	}

	idempotent, err := (addonservice.Manager{Dir: dir}).Add("seo")
	if err != nil {
		t.Fatal(err)
	}
	if idempotent.Changed() {
		t.Fatalf("idempotent changes = %#v", idempotent.Result.Files)
	}

	writeFile(t, dir, "plugin/files/controller.go", strings.Replace(controllerSource, "true", "false", 1))
	if _, err := (addonservice.Manager{Dir: dir}).Update(); err == nil || !strings.Contains(err.Error(), "immutable") {
		t.Fatalf("changed artifact immutability error = %v", err)
	}
	writeFile(t, dir, "plugin/files/controller.go", controllerSource)

	installedController := readFile(t, dir, "app/controllers/seo_addon.go")
	writeFile(t, dir, "app/controllers/seo_addon.go", installedController+"// local change\n")
	if _, err := manager.Remove("seo"); err == nil || !strings.Contains(err.Error(), "local changes") {
		t.Fatalf("contributed file drift error = %v", err)
	}
	writeFile(t, dir, "app/controllers/seo_addon.go", installedController)

	remove, err := manager.Remove("seo")
	if err != nil {
		t.Fatal(err)
	}
	if err := remove.Apply(); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"app/controllers/seo_addon.go", "app/controllers/custom_addon.go", ".mise/tasks/seo/check"} {
		if _, err := os.Stat(filepath.Join(dir, filepath.FromSlash(name))); !os.IsNotExist(err) {
			t.Fatalf("removed contribution %s still exists: %v", name, err)
		}
	}
	packageJSON = readFile(t, dir, "package.json")
	if strings.Contains(packageJSON, "@scope/seo") || !strings.Contains(packageJSON, `"kept": "4.5.6"`) {
		t.Fatalf("package.json after removal =\n%s", packageJSON)
	}
	jsManifest = readFile(t, dir, "js.toml")
	if strings.Contains(jsManifest, "entrypoint.seo") || !strings.Contains(jsManifest, "entrypoint.turbo") {
		t.Fatalf("js.toml after removal =\n%s", jsManifest)
	}
	if got := requirementVersion(mustParseGoMod(t, readFile(t, dir, "go.mod")), "golazy.dev"); got != "v0.1.20" {
		t.Fatalf("restored framework version = %q", got)
	}
}

