func TestJavaScriptOwnershipSharesRestoresConflictsAndDetectsDrift(t *testing.T) {
	dir := fixtureApp(t, "v0.1.21")
	if err := os.Remove(filepath.Join(dir, "lazyaddon.toml")); err != nil {
		t.Fatal(err)
	}
	writeFile(t, dir, "package.json", "{\n  \"dependencies\": {\"lit\": \"1.2.3\"},\n  \"private\": true\n}\n")
	writeFile(t, dir, "js.toml", "[entrypoint.lit]\nmodule = \"lit\"\n")
	alpha := memoryAddon("alpha", "v1.0.0")
	alpha.JavaScript.Libraries = []string{"lit@1.2.3"}
	alpha.JavaScript.Entrypoints = []string{"lit=lit"}
	beta := memoryAddon("beta", "v1.0.0")
	beta.JavaScript = alpha.JavaScript
	manager := addonservice.Manager{Dir: dir, Sources: []addonservice.Source{addonservice.MemorySource{Name: "memory:js", Addons: []addonservice.ResolvedAddon{alpha, beta}}}}
	for _, id := range []string{"alpha", "beta"} {
		plan, err := manager.Add(id)
		if err != nil {
			t.Fatal(err)
		}
		if err := plan.Apply(); err != nil {
			t.Fatal(err)
		}
	}
	state, err := addonservice.ReadState(dir)
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Join(managedFile(state, "package.json").Owners, ","); got != "alpha,beta" {
		t.Fatalf("JavaScript file owners = %q", got)
	}
	remove, err := manager.Remove("alpha")
	if err != nil {
		t.Fatal(err)
	}
	if err := remove.Apply(); err != nil {
		t.Fatal(err)
	}
	writeFile(t, dir, "package.json", strings.Replace(readFile(t, dir, "package.json"), `"lit": "1.2.3"`, `"lit": "9.9.9"`, 1))
	if _, err := manager.Remove("beta"); err == nil || !strings.Contains(err.Error(), "drifted") {
		t.Fatalf("JavaScript property drift error = %v", err)
	}
	writeFile(t, dir, "package.json", strings.Replace(readFile(t, dir, "package.json"), `"lit": "9.9.9"`, `"lit": "1.2.3"`, 1))
	remove, err = manager.Remove("beta")
	if err != nil {
		t.Fatal(err)
	}
	if err := remove.Apply(); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(readFile(t, dir, "package.json"), `"lit": "1.2.3"`) || !strings.Contains(readFile(t, dir, "js.toml"), "entrypoint.lit") {
		t.Fatal("pre-existing JavaScript values were not restored")
	}

	beta.JavaScript.Libraries = []string{"lit@2.0.0"}
	manager = addonservice.Manager{Dir: dir, Sources: []addonservice.Source{addonservice.MemorySource{Name: "memory:conflict", Addons: []addonservice.ResolvedAddon{alpha, beta}}}}
	install, err := manager.Add("alpha")
	if err != nil {
		t.Fatal(err)
	}
	if err := install.Apply(); err != nil {
		t.Fatal(err)
	}
	if _, err := manager.Add("beta"); err == nil || !strings.Contains(err.Error(), "library conflict") {
		t.Fatalf("JavaScript version conflict = %v", err)
	}
}

