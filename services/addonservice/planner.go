const generatedAddonsHeader = "// Code generated by lazy add-ons. DO NOT EDIT."

// Manager plans add-on state changes for one application root.
type Manager struct {
	Dir           string
	ManifestPaths []string
	Sources       []Source
	Context       context.Context
	// FrameworkVersion pins the runtime API used by generated add-on wiring.
	// Empty uses InstallerFrameworkVersion.
	FrameworkVersion string
}

// Plan is a baseline-bound, dry-run friendly add-on changeset.
type Plan struct {
	Dir         string
	Action      string
	Before      State
	After       State
	Result      lazycode.Result
	Modes       map[string]os.FileMode
	ModeChanges []FileModeEdit
}

// FileModeEdit is one baseline-bound permission change for an existing
// installer-owned file whose bytes did not otherwise change.
type FileModeEdit struct {
	Path         string
	BaselineHash string
	Before       uint32
	After        uint32
}

func (plan Plan) Changed() bool { return plan.Result.Changed() || len(plan.ModeChanges) != 0 }

// Add installs or promotes one direct add-on. spec accepts id or id@vX.Y.Z.
func (manager Manager) Add(spec string) (Plan, error) {
	return manager.AddWithOptions(spec, AddOptions{})
}

// AddConfigured installs or promotes one direct add-on and merges the given
// non-secret runtime configuration into its desired state.
func (manager Manager) AddConfigured(spec string, config map[string]string) (Plan, error) {
	return manager.AddWithOptions(spec, AddOptions{Config: config})
}

// AddOptions controls application-specific desired state for AddWithOptions.
// Config values are committed non-secrets. UnsetConfig removes inherited
// values from an already installed direct or transitive add-on.
type AddOptions struct {
	Config      map[string]string
	UnsetConfig []string
}

// AddWithOptions installs or promotes one direct add-on and updates its
// application-specific configuration in the same transactional plan.
func (manager Manager) AddWithOptions(spec string, options AddOptions) (Plan, error) {
	id, version, err := ParseSpec(spec)
	if err != nil {
		return Plan{}, err
	}
	if err := validateAddonConfig(options.Config); err != nil {
		return Plan{}, err
	}
	for _, key := range options.UnsetConfig {
		if !validConfigKey(key) {
			return Plan{}, fmt.Errorf("add-on configuration key %q is invalid", key)
		}
	}
	state, err := manager.readState()
	if err != nil {
		return Plan{}, err
	}
	direct := directQueries(state)
	found := false
	for index := range direct {
		if direct[index].ID != id {
			continue
		}
		found = true
		if version != "" {
			direct[index].Version = version
		}
	}
	if !found {
		direct = append(direct, Query{ID: id, Version: version})
	}
	pinned := pinnedVersions(state)
	delete(pinned, id)
	if version != "" {
		pinned[id] = version
	}
	configs := installedConfigs(state)
	if len(options.Config) != 0 || len(options.UnsetConfig) != 0 {
		configured := configs[id]
		if configured == nil {
			configured = map[string]string{}
		}
		for key, value := range options.Config {
			configured[key] = value
		}
		for _, key := range options.UnsetConfig {
			delete(configured, key)
		}
		if len(configured) == 0 {
			delete(configs, id)
		} else {
			configs[id] = configured
		}
	}
	return manager.plan("add "+id, state, direct, pinned, configs)
}

// Remove removes a directly selected add-on and any now-unneeded dependencies.
func (manager Manager) Remove(id string) (Plan, error) {
	id = strings.TrimSpace(id)
	if id == "" {
		return Plan{}, fmt.Errorf("add-on ID is required")
	}
	state, err := manager.readState()
	if err != nil {
		return Plan{}, err
	}
	direct := directQueries(state)
	found := false
	filtered := direct[:0]
	for _, query := range direct {
		if query.ID == id {
			found = true
			continue
		}
		filtered = append(filtered, query)
	}
	if !found {
		if installed, ok := state.addon(id); ok && !installed.Direct {
			return Plan{}, fmt.Errorf("add-on %q is required by another add-on and is not directly installed", id)
		}
		return Plan{}, fmt.Errorf("add-on %q is not installed", id)
	}
	return manager.plan("remove "+id, state, filtered, pinnedVersions(state), installedConfigs(state))
}

// Update resolves the newest exact versions from configured sources. With no
// IDs it updates every direct add-on.
func (manager Manager) Update(ids ...string) (Plan, error) {
	state, err := manager.readState()
	if err != nil {
		return Plan{}, err
	}
	if len(state.Addons) == 0 {
		root, rootErr := manager.root()
		if rootErr != nil {
			return Plan{}, rootErr
		}
		return Plan{Dir: root, Action: "update", Before: state, After: state}, nil
	}
	targets := map[string]bool{}
	if len(ids) == 0 {
		for _, addon := range state.Addons {
			if addon.Direct {
				targets[addon.ID] = true
			}
		}
	} else {
		for _, id := range ids {
			id = strings.TrimSpace(id)
			addon, ok := state.addon(id)
			if !ok {
				return Plan{}, fmt.Errorf("add-on %q is not installed", id)
			}
			if !addon.Direct {
				return Plan{}, fmt.Errorf("add-on %q is transitive; update its direct owner or all add-ons", id)
			}
			targets[id] = true
		}
	}
	direct := directQueries(state)
	closure := dependencyClosure(state, targets)
	for index := range direct {
		if closure[direct[index].ID] {
			direct[index].Version = ""
		}
	}
	pinned := pinnedVersions(state)
	for id := range closure {
		delete(pinned, id)
	}
	return manager.plan("update", state, direct, pinned, installedConfigs(state))
}

// dependencyClosure returns only the locked dependency graph reachable from
// the requested direct add-ons. Newly introduced dependencies are naturally
// unpinned because they do not exist in the locked state; unrelated branches
// retain their exact versions.
func dependencyClosure(state State, roots map[string]bool) map[string]bool {
	closure := make(map[string]bool, len(roots))
	var visit func(string)
	visit = func(id string) {
		if closure[id] {
			return
		}
		closure[id] = true
		addon, ok := state.addon(id)
		if !ok {
			return
		}
		for _, requirement := range addon.Requires {
			required, _, err := ParseSpec(requirement)
			if err == nil {
				visit(required)
			}
		}
	}
	for id := range roots {
		visit(id)
	}
	return closure
}

func ParseSpec(spec string) (id, version string, err error) {
	spec = strings.TrimSpace(spec)
	if spec == "" {
		return "", "", fmt.Errorf("add-on ID is required")
	}
	if at := strings.LastIndexByte(spec, '@'); at > 0 {
		id, version = strings.TrimSpace(spec[:at]), strings.TrimSpace(spec[at+1:])
	} else {
		id = spec
	}
	if id == "" {
		return "", "", fmt.Errorf("add-on ID is required")
	}
	if version != "" && !exactVersion(version) {
		return "", "", fmt.Errorf("add-on %q requested non-exact version %q", id, version)
	}
	return id, version, nil
}

func (manager Manager) plan(action string, before State, direct []Query, pinned map[string]string, configs map[string]map[string]string) (Plan, error) {
	root, err := manager.root()
	if err != nil {
		return Plan{}, err
	}
	catalog, err := manager.catalog(root, before)
	if err != nil {
		return Plan{}, err
	}
	addons, err := resolveSelection(manager.context(), catalog, direct, pinned, configs)
	if err != nil {
		return Plan{}, err
	}
	if err := verifyImmutableReleases(before, addons); err != nil {
		return Plan{}, err
	}
	after := State{Manifest: 1, Addons: addons}
	workspace, current, currentModes, err := loadWorkspace(root, before, addons)
	if err != nil {
		return Plan{}, err
	}
	if err := verifyManagedBaselines(before, current, currentModes); err != nil {
		return Plan{}, err
	}
	goMod, modules, err := reconcileModules(current[GoModFilename], before, addons, manager.frameworkVersion())
	if err != nil {
		return Plan{}, err
	}
	after.Modules = modules
	applicationModule := modfile.ModulePath(current[GoModFilename])
	if err := module.CheckImportPath(applicationModule); err != nil {
		return Plan{}, fmt.Errorf("%s module path: %w", GoModFilename, err)
	}
	operations := make([]lazycode.Operation, 0, 4)
	if len(addons) == 0 {
		operations = append(operations,
			gocode.Rewrite(ApplicationFilename, removeInstalledAddonsField),
			lazycode.OperationFunc(func(workspace *lazycode.Workspace) error {
				return workspace.Remove(GeneratedFilename)
			}),
		)
	} else {
		if err := verifyGeneratedFileOwnership(before, current); err != nil {
			return Plan{}, err
		}
		generated := renderGeneratedAddons(addons, applicationModule)
		operations = append(operations,
			gocode.Rewrite(ApplicationFilename, ensureInstalledAddonsField),
			gocode.EnsureFile(GeneratedFilename, generated),
		)
	}
	operations = append(operations, lazycode.OperationFunc(func(workspace *lazycode.Workspace) error {
		return workspace.Replace(GoModFilename, goMod)
	}))
	contributionOperations, contributionFiles, err := postgresContributions(before, addons, current)
	if err != nil {
		return Plan{}, err
	}
	operations = append(operations, contributionOperations...)
	genericOperations, genericFiles, err := genericContributions(before, addons, current)
	if err != nil {
		return Plan{}, err
	}
	operations = append(operations, genericOperations...)
	contributionFiles = append(contributionFiles, genericFiles...)
	sourceEditOperations, sourceEditFiles, err := sourceEditContributions(before, addons, current)
	if err != nil {
		return Plan{}, err
	}
	operations = append(operations, sourceEditOperations...)
	contributionFiles = append(contributionFiles, sourceEditFiles...)
	contributionFiles, err = mergeContributionFiles(contributionFiles)
	if err != nil {
		return Plan{}, err
	}
	if err := validatePlannedBuildHooks(addons, contributionFiles); err != nil {
		return Plan{}, err
	}
	preliminary, err := workspace.Plan(operations...)
	if err != nil {
		return Plan{}, fmt.Errorf("plan add-on source changes: %w", err)
	}
	targets := targetFiles(current, preliminary)
	if len(addons) != 0 {
		after.Managed = []ManagedFile{
			{Path: ApplicationFilename, Kind: "rewrite", Owners: []string{"golazy/addons"}, Baseline: lazycode.Hash(targets[ApplicationFilename]), Mode: 0o644},
			{Path: GeneratedFilename, Kind: "generated", Owners: installedIDs(addons), Baseline: lazycode.Hash(targets[GeneratedFilename]), Mode: 0o644},
		}
	}
	for _, file := range contributionFiles {
		file.Baseline = lazycode.Hash(targets[file.Path])
		after.Managed = append(after.Managed, file)
	}
	preserveApplicationModes(after.Managed, currentModes)
	modeChanges, err := plannedModeChanges(currentModes, preliminary, after.Managed)
	if err != nil {
		return Plan{}, err
	}
	if len(addons) == 0 {
		operations = append(operations, lazycode.OperationFunc(func(workspace *lazycode.Workspace) error {
			return workspace.Remove(StateFilename)
		}))
	} else {
		stateData, err := MarshalState(after)
		if err != nil {
			return Plan{}, fmt.Errorf("render %s: %w", StateFilename, err)
		}
		operations = append(operations, lazycode.OperationFunc(func(workspace *lazycode.Workspace) error {
			return workspace.Replace(StateFilename, stateData)
		}))
	}
	result, err := workspace.Plan(operations...)
	if err != nil {
		return Plan{}, fmt.Errorf("plan add-on changes: %w", err)
	}
	return Plan{Dir: root, Action: action, Before: before, After: after, Result: result, Modes: modesFromManaged(after.Managed), ModeChanges: modeChanges}, nil
}

func verifyImmutableReleases(before State, resolved []InstalledAddon) error {
	for _, addon := range resolved {
		locked, ok := before.addon(addon.ID)
		if !ok || locked.Version != addon.Version {
			continue
		}
		if locked.ManifestDigest == addon.ManifestDigest && locked.Source == addon.Source {
			continue
		}
		return fmt.Errorf("add-on %q release %s changed source or manifest digest; published add-on versions are immutable", addon.ID, addon.Version)
	}
	return nil
}

func verifyGeneratedFileOwnership(before State, current map[string][]byte) error {
	data, exists := current[GeneratedFilename]
	if !exists {
		return nil
	}
	if _, managed := before.managedFile(GeneratedFilename); managed {
		return nil
	}
	if bytes.HasPrefix(data, []byte(generatedAddonsHeader)) {
		return nil
	}
	return fmt.Errorf("%s already exists and is not recognized as a GoLazy-generated add-on file", GeneratedFilename)
}

func preserveApplicationModes(files []ManagedFile, current map[string]os.FileMode) {
	for index := range files {
		file := &files[index]
		if file.Kind == "generated" || file.Kind == "addon-file" {
			continue
		}
		if mode, exists := current[file.Path]; exists {
			file.Mode = uint32(mode.Perm())
		} else if file.Mode == 0 {
			file.Mode = 0o644
		}
	}
}

func modesFromManaged(files []ManagedFile) map[string]os.FileMode {
	modes := make(map[string]os.FileMode, len(files))
	for _, file := range files {
		if file.Mode != 0 {
			modes[file.Path] = os.FileMode(file.Mode)
		}
	}
	return modes
}

func (manager Manager) readState() (State, error) {
	root, err := manager.root()
	if err != nil {
		return State{}, err
	}
	return ReadState(root)
}

func (manager Manager) root() (string, error) {
	if strings.TrimSpace(manager.Dir) != "" {
		return filepath.Abs(manager.Dir)
	}
	return os.Getwd()
}

func (manager Manager) context() context.Context {
	if manager.Context != nil {
		return manager.Context
	}
	return context.Background()
}

func (manager Manager) frameworkVersion() string {
	if version := strings.TrimSpace(manager.FrameworkVersion); version != "" {
		return version
	}
	return InstallerFrameworkVersion
}

func (manager Manager) catalog(root string, state State) (Catalog, error) {
	var sources []Source
	explicitPaths := append([]string(nil), manager.ManifestPaths...)
	if len(explicitPaths) == 0 {
		if _, err := os.Stat(filepath.Join(root, "lazyaddon.toml")); err == nil {
			explicitPaths = append(explicitPaths, "lazyaddon.toml")
		} else if err != nil && !errors.Is(err, os.ErrNotExist) {
			return Catalog{}, fmt.Errorf("inspect lazyaddon.toml: %w", err)
		}
	}
	paths := append([]string(nil), explicitPaths...)
	for _, addon := range state.Addons {
		if strings.HasPrefix(addon.Source, "local:") {
			path := strings.TrimPrefix(addon.Source, "local:")
			fullPath := path
			if !filepath.IsAbs(fullPath) {
				fullPath = filepath.Join(root, filepath.FromSlash(fullPath))
			}
			if _, err := os.Stat(fullPath); err == nil {
				paths = append(paths, path)
			} else if err != nil && !errors.Is(err, os.ErrNotExist) {
				return Catalog{}, fmt.Errorf("inspect recorded add-on manifest %s: %w", path, err)
			}
		}
	}
	seen := map[string]bool{}
	for _, path := range paths {
		source := LocalManifestSource{Root: root, Path: path}
		if seen[source.ID()] {
			continue
		}
		seen[source.ID()] = true
		sources = append(sources, source)
	}
	sources = append(sources, manager.Sources...)
	sources = append(sources, StateSource{State: state})
	return Catalog{Sources: sources}, nil
}

func directQueries(state State) []Query {
	var queries []Query
	for _, addon := range state.Addons {
		if addon.Direct {
			queries = append(queries, Query{ID: addon.ID, Version: addon.Version})
		}
	}
	sort.Slice(queries, func(i, j int) bool { return queries[i].ID < queries[j].ID })
	return queries
}

func pinnedVersions(state State) map[string]string {
	versions := make(map[string]string, len(state.Addons))
	for _, addon := range state.Addons {
		versions[addon.ID] = addon.Version
	}
	return versions
}

func installedConfigs(state State) map[string]map[string]string {
	configs := make(map[string]map[string]string, len(state.Addons))
	for _, addon := range state.Addons {
		if len(addon.Config) != 0 {
			configs[addon.ID] = cloneConfig(addon.Config)
		}
	}
	return configs
}

func loadWorkspace(root string, state State, addons []InstalledAddon) (*lazycode.Workspace, map[string][]byte, map[string]os.FileMode, error) {
	workspace := lazycode.New(root)
	files := map[string][]byte{}
	modes := map[string]os.FileMode{}
	names := []string{StateFilename, GeneratedFilename, ApplicationFilename, GoModFilename}
	names = append(names, postgresOutputPaths()...)
	for _, addon := range addons {
		for _, artifact := range addon.Artifacts {
			names = append(names, artifact.Target)
		}
		targets, err := sourceEditTargetPaths([]InstalledAddon{addon})
		if err != nil {
			return nil, nil, nil, err
		}
		names = append(names, targets...)
		if len(addon.JavaScript.Libraries) != 0 {
			names = append(names, packageJSONFilename)
		}
		if len(addon.JavaScript.Entrypoints) != 0 {
			names = append(names, jsManifestFilename)
		}
	}
	for _, managed := range state.Managed {
		names = append(names, managed.Path)
	}
	seen := map[string]bool{}
	for _, name := range names {
		if seen[name] {
			continue
		}
		seen[name] = true
		data, mode, exists, err := readAddonTarget(root, name)
		if err != nil {
			return nil, nil, nil, err
		}
		if !exists {
			if name != ApplicationFilename && name != GoModFilename {
				continue
			}
			return nil, nil, nil, fmt.Errorf("read %s: %w", name, os.ErrNotExist)
		}
		files[name] = data
		modes[name] = mode
		if err := workspace.Add(name, data); err != nil {
			return nil, nil, nil, err
		}
	}
	return workspace, files, modes, nil
}

func verifyManagedBaselines(state State, current map[string][]byte, modes map[string]os.FileMode) error {
	for _, managed := range state.Managed {
		if managed.Kind != "generated" && managed.Kind != "addon-file" && managed.Kind != "addon-shared" {
			continue
		}
		data, exists := current[managed.Path]
		if !exists {
			return fmt.Errorf("managed file %s is missing; restore it or remove its entry from %s deliberately", managed.Path, StateFilename)
		}
		if lazycode.Hash(data) != managed.Baseline {
			return fmt.Errorf("managed file %s has local changes; expected %s", managed.Path, managed.Baseline)
		}
		if managed.Kind != "addon-shared" && managed.Mode != 0 && modes[managed.Path].Perm() != os.FileMode(managed.Mode).Perm() {
			return fmt.Errorf("managed file %s has mode %o; expected %o", managed.Path, modes[managed.Path].Perm(), os.FileMode(managed.Mode).Perm())
		}
	}
	return nil
}

func plannedModeChanges(current map[string]os.FileMode, result lazycode.Result, managed []ManagedFile) ([]FileModeEdit, error) {
	contentEdits := make(map[string]bool, len(result.Files))
	for _, edit := range result.Files {
		contentEdits[edit.Path] = true
	}
	var changes []FileModeEdit
	for _, file := range managed {
		if file.Mode == 0 || contentEdits[file.Path] {
			continue
		}
		before, exists := current[file.Path]
		if !exists {
			continue
		}
		want := os.FileMode(file.Mode).Perm()
		if before.Perm() == want {
			continue
		}
		if file.Kind == "addon-shared" {
			return nil, fmt.Errorf("shared application file %s has mode %o, but the add-on artifact requires %o", file.Path, before.Perm(), want)
		}
		if file.Kind != "generated" && file.Kind != "addon-file" {
			continue
		}
		changes = append(changes, FileModeEdit{Path: file.Path, BaselineHash: file.Baseline, Before: uint32(before.Perm()), After: uint32(want)})
	}
	sort.Slice(changes, func(i, j int) bool { return changes[i].Path < changes[j].Path })
	return changes, nil
}

func targetFiles(current map[string][]byte, result lazycode.Result) map[string][]byte {
	targets := make(map[string][]byte, len(current)+len(result.Files))
	for name, data := range current {
		targets[name] = append([]byte(nil), data...)
	}
	for _, edit := range result.Files {
		if edit.Kind == lazycode.EditDelete {
			delete(targets, edit.Path)
		} else {
			targets[edit.Path] = append([]byte(nil), edit.After...)
		}
	}
	return targets
}

func installedIDs(addons []InstalledAddon) []string {
	ids := make([]string, len(addons))
	for index, addon := range addons {
		ids[index] = addon.ID
	}
	return normalizedStrings(ids)
}

func renderGeneratedAddons(addons []InstalledAddon, modulePath string) []byte {
	imports := map[string]bool{}
	type selectedAddon struct {
		id      string
		version string
	}
	selected := make([]selectedAddon, 0, len(addons)+1)
	for _, addon := range addons {
		imports[addon.GoImport] = true
		selected = append(selected, selectedAddon{id: addon.ID, version: addon.Version})
	}
	importPaths := make([]string, 0, len(imports))
	for path := range imports {
		importPaths = append(importPaths, path)
	}
	sort.Strings(importPaths)
	sort.Slice(selected, func(i, j int) bool { return selected[i].id < selected[j].id })
	postgresVersion := ""
	if postgresOutputsEnabled(addons) {
		for _, addon := range addons {
			if addon.ID == "postgres" {
				postgresVersion = addon.Version
				break
			}
		}
		selected = append(selected, selectedAddon{id: "application/postgres", version: postgresVersion})
	}
	var source strings.Builder
	source.WriteString(generatedAddonsHeader + "\n\n")
	source.WriteString("package appinit\n\n")
	source.WriteString("import (\n\t\"golazy.dev/lazyaddon\"\n")
	if postgresOutputsEnabled(addons) {
		source.WriteString("\t\"golazy.dev/lazyapp\"\n")
		fmt.Fprintf(&source, "\tappPostgres %s\n", strconv.Quote(strings.TrimSuffix(modulePath, "/")+"/db/postgres"))
	}
	for _, path := range importPaths {
		fmt.Fprintf(&source, "\t_ %s\n", strconv.Quote(path))
	}
	source.WriteString(")\n\n")
	if postgresOutputsEnabled(addons) {
		source.WriteString("var appPostgresRegistration = lazyaddon.MustRegisterDefinition(lazyaddon.Definition{\n")
		source.WriteString("\tID:       \"application/postgres\",\n")
		fmt.Fprintf(&source, "\tVersion:  %s,\n", strconv.Quote(postgresVersion))
		source.WriteString("\tRequires: []string{\"postgres\"},\n")
		source.WriteString("})\n\n")
	}
	source.WriteString("func installedAddons() lazyaddon.Selection {\n")
	source.WriteString("\treturn lazyaddon.Selection{Addons: []lazyaddon.Use{\n")
	for _, addon := range selected {
		fmt.Fprintf(&source, "\t\t{ID: %s, Version: %s", strconv.Quote(addon.id), strconv.Quote(addon.version))
		if installed, exists := installedAddon(addons, addon.id); exists && len(installed.Config) != 0 {
			source.WriteString(", Config: map[string]string{")
			keys := make([]string, 0, len(installed.Config))
			for key := range installed.Config {
				keys = append(keys, key)
			}
			sort.Strings(keys)
			for _, key := range keys {
				fmt.Fprintf(&source, "%s: %s,", strconv.Quote(key), strconv.Quote(installed.Config[key]))
			}
			source.WriteString("}")
		}
		source.WriteString("},\n")
	}
	source.WriteString("\t}}\n}\n")
	if postgresOutputsEnabled(addons) {
		source.WriteString("\nfunc init() {\n")
		source.WriteString("\tlazyaddon.MustOn(appPostgresRegistration, lazyapp.MigrationsHook, lazyaddon.CallbackOptions{\n")
		source.WriteString("\t\tID:    \"app/postgres/migrations\",\n")
		source.WriteString("\t\tAfter: []string{\"postgres/migrations\"},\n")
		source.WriteString("\t}, func(event *lazyapp.MigrationsEvent) error {\n")
		source.WriteString("\t\treturn event.Catalog.Mount(\"postgres\", \"application\", appPostgres.Files())\n")
		source.WriteString("\t})\n}\n")
	}
	return []byte(source.String())
}

func installedAddon(addons []InstalledAddon, id string) (InstalledAddon, bool) {
	for _, addon := range addons {
		if addon.ID == id {
			return addon, true
		}
	}
	return InstalledAddon{}, false
}

func ensureInstalledAddonsField(_ *token.FileSet, file *ast.File) (bool, error) {
	target, err := lazyappConfig(file)
	if err != nil {
		return false, fmt.Errorf("%s: %w", ApplicationFilename, err)
	}
	for _, element := range target.Elts {
		field, ok := element.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		name, ok := field.Key.(*ast.Ident)
		if !ok || name.Name != "Addons" {
			continue
		}
		if !isInstalledAddonsCall(field.Value) {
			return false, fmt.Errorf("%s already configures Addons; merge installedAddons() manually", ApplicationFilename)
		}
		return false, nil
	}
	target.Elts = append(target.Elts, &ast.KeyValueExpr{
		Key: ast.NewIdent("Addons"),
		Value: &ast.CallExpr{
			Fun: ast.NewIdent("installedAddons"),
		},
	})
	return true, nil
}

func removeInstalledAddonsField(_ *token.FileSet, file *ast.File) (bool, error) {
	target, err := lazyappConfig(file)
	if err != nil {
		return false, fmt.Errorf("%s: %w", ApplicationFilename, err)
	}
	for index, element := range target.Elts {
		field, ok := element.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		name, ok := field.Key.(*ast.Ident)
		if !ok || name.Name != "Addons" {
			continue
		}
		if !isInstalledAddonsCall(field.Value) {
			return false, fmt.Errorf("%s Addons configuration is no longer installer-owned; remove it manually", ApplicationFilename)
		}
		target.Elts = append(target.Elts[:index], target.Elts[index+1:]...)
		return true, nil
	}
	return false, nil
}

func lazyappConfig(file *ast.File) (*ast.CompositeLit, error) {
	alias, err := importedPackageName(file, "golazy.dev/lazyapp")
	if err != nil {
		return nil, err
	}
	var appFunctions []*ast.FuncDecl
	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if ok && function.Recv == nil && function.Name.Name == "App" && function.Body != nil {
			appFunctions = append(appFunctions, function)
		}
	}
	if len(appFunctions) != 1 {
		return nil, fmt.Errorf("expected exactly one App function, found %d", len(appFunctions))
	}
	function := appFunctions[0]
	var constructors []*ast.CallExpr
	ast.Inspect(function.Body, func(node ast.Node) bool {
		if _, nested := node.(*ast.FuncLit); nested {
			return false
		}
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}
		selector, ok := call.Fun.(*ast.SelectorExpr)
		identifier, named := selectorXIdentifier(selector)
		if ok && named && identifier.Name == alias && selector.Sel.Name == "New" {
			constructors = append(constructors, call)
		}
		return true
	})
	if len(constructors) != 1 {
		return nil, fmt.Errorf("App must contain exactly one %s.New call, found %d", alias, len(constructors))
	}
	constructor := constructors[0]
	if len(constructor.Args) != 1 {
		return nil, fmt.Errorf("%s.New must receive one Config value", alias)
	}
	if literal := lazyappConfigLiteral(constructor.Args[0], alias); literal != nil {
		return literal, nil
	}
	if call, ok := constructor.Args[0].(*ast.CallExpr); ok && len(call.Args) == 0 {
		if factory, ok := call.Fun.(*ast.Ident); ok && factory.Name == "Config" {
			return configFunctionLiteral(file, alias, factory.Name)
		}
	}
	identifier, ok := constructor.Args[0].(*ast.Ident)
	if !ok {
		return nil, fmt.Errorf("%s.New Config argument is not a literal or local identifier", alias)
	}
	bindings := localConfigBindings(function.Body, constructor.Pos(), identifier.Name, alias)
	if len(bindings) != 1 {
		return nil, fmt.Errorf("Config identifier %q has %d unambiguous local literal bindings", identifier.Name, len(bindings))
	}
	return bindings[0], nil
}

func configFunctionLiteral(file *ast.File, alias, name string) (*ast.CompositeLit, error) {
	var functions []*ast.FuncDecl
	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if ok && function.Recv == nil && function.Name.Name == name && function.Body != nil {
			functions = append(functions, function)
		}
	}
	if len(functions) != 1 {
		return nil, fmt.Errorf("expected exactly one %s function, found %d", name, len(functions))
	}
	var literals []*ast.CompositeLit
	ast.Inspect(functions[0].Body, func(node ast.Node) bool {
		if _, nested := node.(*ast.FuncLit); nested {
			return false
		}
		statement, ok := node.(*ast.ReturnStmt)
		if !ok || len(statement.Results) != 1 {
			return true
		}
		if literal := lazyappConfigLiteral(statement.Results[0], alias); literal != nil {
			literals = append(literals, literal)
			return true
		}
		if identifier, ok := statement.Results[0].(*ast.Ident); ok {
			literals = append(literals, localConfigBindings(functions[0].Body, statement.Pos(), identifier.Name, alias)...)
		}
		return true
	})
	if len(literals) != 1 {
		return nil, fmt.Errorf("%s has %d unambiguous returned %s.Config literals", name, len(literals), alias)
	}
	return literals[0], nil
}

func importedPackageName(file *ast.File, importPath string) (string, error) {
	var names []string
	for _, spec := range file.Imports {
		value, err := strconv.Unquote(spec.Path.Value)
		if err != nil || value != importPath {
			continue
		}
		name := path.Base(importPath)
		if spec.Name != nil {
			name = spec.Name.Name
		}
		if name == "_" || name == "." {
			return "", fmt.Errorf("%s must use a named import", importPath)
		}
		names = append(names, name)
	}
	if len(names) != 1 {
		return "", fmt.Errorf("expected exactly one %s import, found %d", importPath, len(names))
	}
	return names[0], nil
}

func selectorXIdentifier(selector *ast.SelectorExpr) (*ast.Ident, bool) {
	if selector == nil {
		return nil, false
	}
	identifier, ok := selector.X.(*ast.Ident)
	return identifier, ok
}

func lazyappConfigLiteral(expression ast.Expr, alias string) *ast.CompositeLit {
	for {
		parenthesized, ok := expression.(*ast.ParenExpr)
		if !ok {
			break
		}
		expression = parenthesized.X
	}
	literal, ok := expression.(*ast.CompositeLit)
	if !ok {
		return nil
	}
	selector, ok := literal.Type.(*ast.SelectorExpr)
	identifier, named := selectorXIdentifier(selector)
	if !ok || !named || identifier.Name != alias || selector.Sel.Name != "Config" {
		return nil
	}
	return literal
}

func localConfigBindings(body *ast.BlockStmt, before token.Pos, name, alias string) []*ast.CompositeLit {
	var bindings []*ast.CompositeLit
	ast.Inspect(body, func(node ast.Node) bool {
		if _, nested := node.(*ast.FuncLit); nested {
			return false
		}
		if node == nil || node.Pos() >= before {
			return node != nil
		}
		switch statement := node.(type) {
		case *ast.AssignStmt:
			for index, left := range statement.Lhs {
				identifier, ok := left.(*ast.Ident)
				if !ok || identifier.Name != name || index >= len(statement.Rhs) {
					continue
				}
				if literal := lazyappConfigLiteral(statement.Rhs[index], alias); literal != nil {
					bindings = append(bindings, literal)
				}
			}
		case *ast.ValueSpec:
			for index, declared := range statement.Names {
				if declared.Name != name || index >= len(statement.Values) {
					continue
				}
				if literal := lazyappConfigLiteral(statement.Values[index], alias); literal != nil {
					bindings = append(bindings, literal)
				}
			}
		}
		return true
	})
	return bindings
}

func isInstalledAddonsCall(expression ast.Expr) bool {
	call, ok := expression.(*ast.CallExpr)
	if !ok || len(call.Args) != 0 {
		return false
	}
	function, ok := call.Fun.(*ast.Ident)
	return ok && function.Name == "installedAddons"
}

type requirementState struct {
	Version  string
	Indirect bool
}

func reconcileModules(data []byte, before State, addons []InstalledAddon, frameworkVersion string) ([]byte, []ManagedModule, error) {
	file, err := modfile.Parse(GoModFilename, data, nil)
	if err != nil {
		return nil, nil, fmt.Errorf("parse %s: %w", GoModFilename, err)
	}
	current := map[string]requirementState{}
	for _, requirement := range file.Require {
		current[requirement.Mod.Path] = requirementState{Version: requirement.Mod.Version, Indirect: requirement.Indirect}
	}
	desiredVersions := map[string]string{}
	desiredOwners := map[string][]string{}
	if len(addons) != 0 {
		if !exactVersion(frameworkVersion) {
			return nil, nil, fmt.Errorf("installer framework version %q is not exact", frameworkVersion)
		}
		requiredFrameworkVersion := frameworkVersion
		if requirement, exists := current["golazy.dev"]; exists && semver.Compare(requirement.Version, requiredFrameworkVersion) > 0 {
			requiredFrameworkVersion = requirement.Version
		}
		desiredVersions["golazy.dev"] = requiredFrameworkVersion
		desiredOwners["golazy.dev"] = []string{"golazy/addons"}
	}
	for _, addon := range addons {
		if previous := desiredVersions[addon.GoModule]; previous != "" && previous != addon.GoModuleVersion {
			return nil, nil, fmt.Errorf("add-ons require conflicting versions of %s: %s and %s", addon.GoModule, previous, addon.GoModuleVersion)
		}
		desiredVersions[addon.GoModule] = addon.GoModuleVersion
		desiredOwners[addon.GoModule] = append(desiredOwners[addon.GoModule], addon.ID)
	}

	target := make(map[string]requirementState, len(current))
	for path, requirement := range current {
		target[path] = requirement
	}
	for _, old := range before.Modules {
		requirement, exists := current[old.Path]
		if !exists || requirement.Version != old.Version || requirement.Indirect {
			return nil, nil, fmt.Errorf("go.mod requirement %s drifted from locked direct version %s", old.Path, old.Version)
		}
		if _, stillRequired := desiredVersions[old.Path]; stillRequired {
			continue
		}
		if old.Managed {
			if old.Previous == "" {
				delete(target, old.Path)
			} else {
				target[old.Path] = requirementState{Version: old.Previous, Indirect: old.PreviousIndirect}
			}
		}
	}

	paths := make([]string, 0, len(desiredVersions))
	for path := range desiredVersions {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	modules := make([]ManagedModule, 0, len(paths))
	for _, path := range paths {
		version := desiredVersions[path]
		old, tracked := before.module(path)
		moduleState := ManagedModule{Path: path, Version: version, Owners: desiredOwners[path]}
		if tracked {
			moduleState.Managed = old.Managed || old.Version != version
			moduleState.Previous = old.Previous
			moduleState.PreviousIndirect = old.PreviousIndirect
		} else if requirement, exists := current[path]; exists {
			moduleState.Managed = requirement.Version != version || requirement.Indirect
			moduleState.Previous = requirement.Version
			moduleState.PreviousIndirect = requirement.Indirect
		} else {
			moduleState.Managed = true
		}
		target[path] = requirementState{Version: version}
		modules = append(modules, moduleState)
	}

	requirements := make([]*modfile.Require, 0, len(target))
	for path, requirement := range target {
		requirements = append(requirements, &modfile.Require{
			Mod:      module.Version{Path: path, Version: requirement.Version},
			Indirect: requirement.Indirect,
		})
	}
	sort.Slice(requirements, func(i, j int) bool { return requirements[i].Mod.Path < requirements[j].Mod.Path })
	file.SetRequire(requirements)
	file.Cleanup()
	formatted, err := file.Format()
	if err != nil {
		return nil, nil, fmt.Errorf("format %s: %w", GoModFilename, err)
	}
	if bytes.Equal(formatted, data) {
		return append([]byte(nil), data...), modules, nil
	}
	return formatted, modules, nil
}
