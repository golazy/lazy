func managedFile(state addonservice.State, name string) addonservice.ManagedFile {
	for _, file := range state.Managed {
		if file.Path == name {
			return file
		}
	}
	return addonservice.ManagedFile{}
}

func fmtManifest(format, mapping string) string {
	return strings.Replace(format, "%s", mapping, 1)
}
