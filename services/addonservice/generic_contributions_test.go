func TestUpdateAppliesModeOnlyArtifactChange(t *testing.T) {
	dir := fixtureApp(t, "v0.1.21")
	writeFile(t, dir, "plugin/lazyaddon.toml", modeManifest("v1.0.0"))
	writeFile(t, dir, "plugin/files/task", "#!/bin/sh\nexit 0\n")
	manager := addonservice.Manager{Dir: dir, ManifestPaths: []string{"plugin/lazyaddon.toml"}}
	install, err := manager.Add("mode")
	if err != nil {
		t.Fatal(err)
	}
	if err := install.Apply(); err != nil {
		t.Fatal(err)
	}
	target := filepath.Join(dir, ".mise/tasks/mode/run")
	if info, err := os.Stat(target); err != nil || info.Mode().Perm() != 0o644 {
		t.Fatalf("installed mode = %v, %v", info, err)
	}

	writeFile(t, dir, "plugin/lazyaddon.toml", modeManifest("v1.0.1"))
	if err := os.Chmod(filepath.Join(dir, "plugin/files/task"), 0o755); err != nil {
		t.Fatal(err)
	}
	update, err := manager.Update()
	if err != nil {
		t.Fatal(err)
	}
	if len(update.ModeChanges) != 1 {
		t.Fatalf("mode changes = %#v", update.ModeChanges)
	}
	change := update.ModeChanges[0]
	if change.Path != ".mise/tasks/mode/run" || change.Before != 0o644 || change.After != 0o755 {
		t.Fatalf("mode change = %#v", change)
	}
	if err := update.Apply(); err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(target)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm() != 0o755 {
		t.Fatalf("updated mode = %o, want 755", info.Mode().Perm())
	}
	state, err := addonservice.ReadState(dir)
	if err != nil {
		t.Fatal(err)
	}
	if got := managedFile(state, ".mise/tasks/mode/run").Mode; got != 0o755 {
		t.Fatalf("locked mode = %o, want 755", got)
	}
}

func TestModeOnlyUpdateIsContentBoundAndRejectsLeafSymlinkSwap(t *testing.T) {
	newFixture := func(t *testing.T) (string, addonservice.Manager) {
		t.Helper()
		dir := fixtureApp(t, "v0.1.21")
		writeFile(t, dir, "plugin/lazyaddon.toml", modeManifest("v1.0.0"))
		writeFile(t, dir, "plugin/files/task", "#!/bin/sh\nexit 0\n")
		if err := os.Chmod(filepath.Join(dir, "plugin/files/task"), 0o755); err != nil {
			t.Fatal(err)
		}
		manager := addonservice.Manager{Dir: dir, ManifestPaths: []string{"plugin/lazyaddon.toml"}}
		install, err := manager.Add("mode")
		if err != nil {
			t.Fatal(err)
		}
		if err := install.Apply(); err != nil {
			t.Fatal(err)
		}
		writeFile(t, dir, "plugin/lazyaddon.toml", modeManifest("v1.0.1"))
		if err := os.Chmod(filepath.Join(dir, "plugin/files/task"), 0o644); err != nil {
			t.Fatal(err)
		}
		return dir, manager
	}

	t.Run("content replacement", func(t *testing.T) {
		dir, manager := newFixture(t)
		update, err := manager.Update()
		if err != nil {
			t.Fatal(err)
		}
		target := filepath.Join(dir, ".mise/tasks/mode/run")
		if err := os.WriteFile(target, []byte("changed\n"), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := update.Apply(); err == nil || !strings.Contains(err.Error(), "changed after add-on planning") {
			t.Fatalf("content-bound mode error = %v", err)
		}
		state, err := addonservice.ReadState(dir)
		if err != nil {
			t.Fatal(err)
		}
		if state.Addons[0].Version != "v1.0.0" {
			t.Fatalf("failed apply changed lock to %s", state.Addons[0].Version)
		}
	})

	t.Run("leaf symlink", func(t *testing.T) {
		dir, manager := newFixture(t)
		update, err := manager.Update()
		if err != nil {
			t.Fatal(err)
		}
		target := filepath.Join(dir, ".mise/tasks/mode/run")
		outside := filepath.Join(t.TempDir(), "outside")
		if err := os.WriteFile(outside, []byte("#!/bin/sh\nexit 0\n"), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.Remove(target); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(outside, target); err != nil {
			t.Fatal(err)
		}
		if err := update.Apply(); err == nil || !strings.Contains(err.Error(), "symbolic link") {
			t.Fatalf("symlink swap error = %v", err)
		}
		info, err := os.Stat(outside)
		if err != nil {
			t.Fatal(err)
		}
		if info.Mode().Perm() != 0o755 {
			t.Fatalf("outside mode = %o, want unchanged 755", info.Mode().Perm())
		}
	})
}

