const (
	packageJSONFilename = "package.json"
	jsManifestFilename  = "js.toml"
	jsPropertyPrefix    = "golazy-js-v1:"
	contributedHeader   = "// Code generated by lazy add-ons. DO NOT EDIT."
)

var reservedContributionTargets = map[string]bool{
	StateFilename:       true,
	GeneratedFilename:   true,
	ApplicationFilename: true,
	GoModFilename:       true,
	packageJSONFilename: true,
	jsManifestFilename:  true,
}

func parseFileMapping(value string) (source, target string, err error) {
	if strings.Count(value, "=>") != 1 {
		return "", "", fmt.Errorf("expected source=>target")
	}
	source, target, _ = strings.Cut(value, "=>")
	source, target = strings.TrimSpace(source), strings.TrimSpace(target)
	if !validFilePath(source) {
		return "", "", fmt.Errorf("invalid relative source path %q", source)
	}
	if !validFilePath(target) {
		return "", "", fmt.Errorf("invalid relative target path %q", target)
	}
	for reserved := range reservedContributionTargets {
		if strings.EqualFold(target, reserved) {
			return "", "", fmt.Errorf("target %q is installer-owned; use its structured contribution", target)
		}
	}
	if path.Ext(target) == ".go" {
		base := path.Base(target)
		if strings.HasPrefix(base, "_") || strings.HasPrefix(base, ".") {
			return "", "", fmt.Errorf("Go target %q would be ignored by the Go toolchain", target)
		}
	}
	first, _, _ := strings.Cut(target, "/")
	if strings.EqualFold(first, ".git") || strings.EqualFold(first, ".secrets") {
		return "", "", fmt.Errorf("target %q is outside the application source surface", target)
	}
	return source, target, nil
}

func prepareContributedFile(target string, data []byte) ([]byte, error) {
	data = append([]byte(nil), data...)
	if path.Ext(target) != ".go" || hasGeneratedNotice(data) {
		return data, nil
	}
	prefix := contributedHeader + "\n\n"
	if bytes.HasPrefix(data, []byte("//go:build ")) || bytes.HasPrefix(data, []byte("// +build ")) {
		// Keep the build-constraint comment group contiguous and leave its
		// existing blank line before the package clause intact.
		prefix = contributedHeader + "\n"
	}
	formatted, err := format.Source(append([]byte(prefix), data...))
	if err != nil {
		return nil, fmt.Errorf("format contributed Go source: %w", err)
	}
	return formatted, nil
}

func hasGeneratedNotice(data []byte) bool {
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "package ") {
			return false
		}
		if strings.HasPrefix(line, "// Code generated ") && strings.HasSuffix(line, " DO NOT EDIT.") {
			return true
		}
	}
	return false
}

func validateJavaScriptContributions(addonID string, contribution JavaScriptContributions) error {
	libraries := map[string]string{}
	for _, value := range contribution.Libraries {
		name, version, err := parseJavaScriptLibrary(value)
		if err != nil {
			return fmt.Errorf("add-on %q JavaScript library %q: %w", addonID, value, err)
		}
		if previous, exists := libraries[name]; exists && previous != version {
			return fmt.Errorf("add-on %q declares conflicting versions of JavaScript library %q", addonID, name)
		}
		libraries[name] = version
	}
	entrypoints := map[string]string{}
	for _, value := range contribution.Entrypoints {
		name, module, err := parseJavaScriptEntrypoint(value)
		if err != nil {
			return fmt.Errorf("add-on %q JavaScript entrypoint %q: %w", addonID, value, err)
		}
		if previous, exists := entrypoints[name]; exists && previous != module {
			return fmt.Errorf("add-on %q declares conflicting modules for JavaScript entrypoint %q", addonID, name)
		}
		entrypoints[name] = module
	}
	return nil
}

func parseJavaScriptLibrary(value string) (name, version string, err error) {
	value = strings.TrimSpace(value)
	at := strings.LastIndexByte(value, '@')
	if at <= 0 || at == len(value)-1 {
		return "", "", fmt.Errorf("expected package@exact-version")
	}
	name, version = value[:at], value[at+1:]
	if !validNPMPackageName(name) {
		return "", "", fmt.Errorf("invalid npm package name %q", name)
	}
	if strings.HasPrefix(version, "v") || !semver.IsValid("v"+version) || semver.Canonical("v"+version) != "v"+version {
		return "", "", fmt.Errorf("npm version %q is not an exact semantic version", version)
	}
	return name, version, nil
}

func validNPMPackageName(name string) bool {
	if name == "" || strings.TrimSpace(name) != name || strings.ContainsAny(name, "\\ \t\r\n") {
		return false
	}
	validatePart := func(part string) bool {
		if part == "" || part == "." || part == ".." {
			return false
		}
		for _, character := range part {
			if character >= 'a' && character <= 'z' || character >= '0' && character <= '9' || strings.ContainsRune("._-", character) {
				continue
			}
			return false
		}
		return true
	}
	if strings.HasPrefix(name, "@") {
		parts := strings.Split(name[1:], "/")
		return len(parts) == 2 && validatePart(parts[0]) && validatePart(parts[1])
	}
	return !strings.Contains(name, "/") && validatePart(name)
}

func parseJavaScriptEntrypoint(value string) (name, module string, err error) {
	name, module, ok := strings.Cut(value, "=")
	name, module = strings.TrimSpace(name), strings.TrimSpace(module)
	if !ok || !validEntrypointName(name) || module == "" {
		return "", "", fmt.Errorf("expected name=module with a bare entrypoint name")
	}
	for _, character := range module {
		if unicode.IsSpace(character) || unicode.IsControl(character) || character == '"' || character == '\'' || character == '`' {
			return "", "", fmt.Errorf("module %q contains unsafe characters", module)
		}
	}
	return name, module, nil
}

func validEntrypointName(name string) bool {
	if name == "" {
		return false
	}
	for _, character := range name {
		if character >= 'a' && character <= 'z' || character >= 'A' && character <= 'Z' || character >= '0' && character <= '9' || character == '_' || character == '-' {
			continue
		}
		return false
	}
	return true
}

func genericContributions(before State, addons []InstalledAddon, current map[string][]byte) ([]lazycode.Operation, []ManagedFile, error) {
	fileOperations, files, err := portableFileContributions(before, addons, current)
	if err != nil {
		return nil, nil, err
	}
	jsOperations, jsFiles, err := javascriptContributions(before, addons, current)
	if err != nil {
		return nil, nil, err
	}
	return append(fileOperations, jsOperations...), append(files, jsFiles...), nil
}

type desiredFile struct {
	data      []byte
	mode      uint32
	owners    []string
	provided  bool
	sourceRef string
}

func portableFileContributions(before State, addons []InstalledAddon, current map[string][]byte) ([]lazycode.Operation, []ManagedFile, error) {
	desired := map[string]desiredFile{}
	byID := make(map[string]InstalledAddon, len(addons))
	for _, addon := range addons {
		byID[addon.ID] = addon
		for _, artifact := range addon.Artifacts {
			entry := desired[artifact.Target]
			if entry.provided && (!bytes.Equal(entry.data, artifact.Data) || entry.mode != artifact.Mode) {
				return nil, nil, fmt.Errorf("add-ons contribute different contents or modes to %s", artifact.Target)
			}
			entry.data = append([]byte(nil), artifact.Data...)
			entry.mode = artifact.Mode
			entry.owners = append(entry.owners, addon.ID)
			entry.provided = true
			entry.sourceRef = artifact.Source
			desired[artifact.Target] = entry
		}
	}

	// Locked snapshots intentionally omit artifact bytes. When their recorded
	// local source is temporarily unavailable, keep the verified installed
	// bytes for mappings that are still declared instead of making an unrelated
	// add/remove depend on that source.
	for _, managed := range before.Managed {
		if managed.Kind != "addon-file" && managed.Kind != "addon-shared" {
			continue
		}
		for _, owner := range managed.Owners {
			addon, active := byID[owner]
			if !active || !declaresFileTarget(addon.Files, managed.Path) {
				continue
			}
			entry := desired[managed.Path]
			if containsString(entry.owners, owner) {
				continue
			}
			data, exists := current[managed.Path]
			if !exists {
				return nil, nil, fmt.Errorf("managed file %s is missing", managed.Path)
			}
			if entry.provided && (!bytes.Equal(entry.data, data) || entry.mode != managed.Mode) {
				return nil, nil, fmt.Errorf("add-ons contribute different contents or modes to %s", managed.Path)
			}
			entry.data = append([]byte(nil), data...)
			entry.mode = managed.Mode
			entry.owners = append(entry.owners, owner)
			entry.provided = true
			desired[managed.Path] = entry
		}
	}

	var operations []lazycode.Operation
	var managedFiles []ManagedFile
	paths := make([]string, 0, len(desired))
	for target := range desired {
		paths = append(paths, target)
	}
	sort.Strings(paths)
	for _, target := range paths {
		entry := desired[target]
		entry.owners = normalizedStrings(entry.owners)
		previous, wasManaged := before.managedFile(target)
		existing, exists := current[target]
		kind := "addon-file"
		if wasManaged {
			if previous.Kind != "addon-file" && previous.Kind != "addon-shared" {
				return nil, nil, fmt.Errorf("%s is already managed as %s", target, previous.Kind)
			}
			kind = previous.Kind
			if kind == "addon-shared" && !bytes.Equal(existing, entry.data) {
				return nil, nil, fmt.Errorf("shared application file %s cannot be replaced by an add-on update", target)
			}
		} else if exists {
			if !bytes.Equal(existing, entry.data) {
				return nil, nil, fmt.Errorf("%s already exists with different contents and is not managed by %s", target, StateFilename)
			}
			kind = "addon-shared"
		}
		if !exists || !bytes.Equal(existing, entry.data) {
			name, data := target, append([]byte(nil), entry.data...)
			operations = append(operations, lazycode.OperationFunc(func(workspace *lazycode.Workspace) error {
				return workspace.Replace(name, data)
			}))
		}
		managedFiles = append(managedFiles, ManagedFile{Path: target, Kind: kind, Owners: entry.owners, Mode: entry.mode})
	}

	for _, previous := range before.Managed {
		if previous.Kind != "addon-file" && previous.Kind != "addon-shared" {
			continue
		}
		if _, remains := desired[previous.Path]; remains {
			continue
		}
		if previous.Kind == "addon-file" {
			name := previous.Path
			operations = append(operations, lazycode.OperationFunc(func(workspace *lazycode.Workspace) error {
				return workspace.Remove(name)
			}))
		}
	}
	return operations, managedFiles, nil
}

func declaresFileTarget(files []string, target string) bool {
	for _, declaration := range files {
		_, declaredTarget, mapped := strings.Cut(declaration, "=>")
		if mapped && strings.TrimSpace(declaredTarget) == target {
			return true
		}
	}
	return false
}

type desiredProperty struct {
	value  string
	owners []string
}

type jsProperty struct {
	Kind     string   `json:"kind"`
	Key      string   `json:"key"`
	Expected string   `json:"expected"`
	Previous *string  `json:"previous,omitempty"`
	Owners   []string `json:"owners"`
}

func javascriptContributions(before State, addons []InstalledAddon, current map[string][]byte) ([]lazycode.Operation, []ManagedFile, error) {
	libraries := map[string]desiredProperty{}
	entrypoints := map[string]desiredProperty{}
	for _, addon := range addons {
		for _, declaration := range addon.JavaScript.Libraries {
			name, version, _ := parseJavaScriptLibrary(declaration)
			if err := mergeDesiredProperty(libraries, name, version, addon.ID); err != nil {
				return nil, nil, fmt.Errorf("JavaScript library conflict: %w", err)
			}
		}
		for _, declaration := range addon.JavaScript.Entrypoints {
			name, module, _ := parseJavaScriptEntrypoint(declaration)
			if err := mergeDesiredProperty(entrypoints, name, module, addon.ID); err != nil {
				return nil, nil, fmt.Errorf("JavaScript entrypoint conflict: %w", err)
			}
		}
	}

	var operations []lazycode.Operation
	var files []ManagedFile
	packageOperation, packageFile, err := reconcilePackageJSON(before, current, libraries)
	if err != nil {
		return nil, nil, err
	}
	if packageOperation != nil {
		operations = append(operations, packageOperation)
	}
	if packageFile != nil {
		files = append(files, *packageFile)
	}
	manifestOperation, manifestFile, err := reconcileJSManifest(before, current, entrypoints)
	if err != nil {
		return nil, nil, err
	}
	if manifestOperation != nil {
		operations = append(operations, manifestOperation)
	}
	if manifestFile != nil {
		files = append(files, *manifestFile)
	}
	return operations, files, nil
}

func mergeDesiredProperty(properties map[string]desiredProperty, key, value, owner string) error {
	property := properties[key]
	if property.value != "" && property.value != value {
		return fmt.Errorf("%q is both %q and %q", key, property.value, value)
	}
	property.value = value
	property.owners = append(property.owners, owner)
	properties[key] = property
	return nil
}

func reconcilePackageJSON(before State, current map[string][]byte, desired map[string]desiredProperty) (lazycode.Operation, *ManagedFile, error) {
	previousFile, wasManaged := before.managedFile(packageJSONFilename)
	previous, err := decodeJSProperties(previousFile.Properties, "dependency")
	if err != nil {
		return nil, nil, fmt.Errorf("decode %s ownership: %w", packageJSONFilename, err)
	}
	source, exists := current[packageJSONFilename]
	document, actual, err := parsePackageJSON(source, exists)
	if err != nil {
		return nil, nil, err
	}
	records, err := reconcileJSProperties("dependency", actual, previous, desired)
	if err != nil {
		return nil, nil, fmt.Errorf("%s: %w", packageJSONFilename, err)
	}
	for key, record := range records.changes {
		if record == nil {
			delete(document.dependencies, key)
		} else {
			document.dependencies[key] = *record
		}
	}
	if len(document.dependencies) == 0 {
		delete(document.root, "dependencies")
	} else {
		document.root["dependencies"] = document.dependencies
	}
	data, err := marshalPackageJSON(document.root)
	if err != nil {
		return nil, nil, err
	}
	remove := len(records.properties) == 0 && wasManaged && previousFile.Kind == "js-created" && len(document.root) == 0
	var operation lazycode.Operation
	if remove {
		operation = lazycode.OperationFunc(func(workspace *lazycode.Workspace) error { return workspace.Remove(packageJSONFilename) })
	} else if len(records.properties) != 0 || wasManaged {
		if !exists || !bytes.Equal(source, data) {
			output := append([]byte(nil), data...)
			operation = lazycode.OperationFunc(func(workspace *lazycode.Workspace) error {
				return workspace.Replace(packageJSONFilename, output)
			})
		}
	}
	if len(records.properties) == 0 {
		return operation, nil, nil
	}
	kind := "js-rewrite"
	if wasManaged {
		kind = previousFile.Kind
	} else if !exists {
		kind = "js-created"
	}
	file := &ManagedFile{Path: packageJSONFilename, Kind: kind, Owners: records.owners, Mode: 0o644, Properties: encodeJSProperties(records.properties)}
	return operation, file, nil
}

type packageDocument struct {
	root                map[string]any
	dependencies        map[string]any
	dependenciesExisted bool
}

func parsePackageJSON(source []byte, exists bool) (packageDocument, map[string]string, error) {
	root := map[string]any{}
	if exists && len(bytes.TrimSpace(source)) != 0 {
		decoder := json.NewDecoder(bytes.NewReader(source))
		decoder.UseNumber()
		if err := decoder.Decode(&root); err != nil {
			return packageDocument{}, nil, fmt.Errorf("parse %s: %w", packageJSONFilename, err)
		}
		var trailing any
		if err := decoder.Decode(&trailing); err == nil {
			return packageDocument{}, nil, fmt.Errorf("parse %s: more than one JSON value", packageJSONFilename)
		} else if err != io.EOF {
			return packageDocument{}, nil, fmt.Errorf("parse %s trailing data: %w", packageJSONFilename, err)
		}
	}
	value, dependenciesExisted := root["dependencies"]
	dependencies := map[string]any{}
	if dependenciesExisted {
		var ok bool
		dependencies, ok = value.(map[string]any)
		if !ok {
			return packageDocument{}, nil, fmt.Errorf("%s dependencies must be an object", packageJSONFilename)
		}
	}
	actual := make(map[string]string, len(dependencies))
	for name, value := range dependencies {
		version, ok := value.(string)
		if !ok {
			return packageDocument{}, nil, fmt.Errorf("%s dependency %q must be a string", packageJSONFilename, name)
		}
		actual[name] = version
	}
	return packageDocument{root: root, dependencies: dependencies, dependenciesExisted: dependenciesExisted}, actual, nil
}

func marshalPackageJSON(document map[string]any) ([]byte, error) {
	data, err := json.MarshalIndent(document, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("format %s: %w", packageJSONFilename, err)
	}
	return append(data, '\n'), nil
}

func reconcileJSManifest(before State, current map[string][]byte, desired map[string]desiredProperty) (lazycode.Operation, *ManagedFile, error) {
	previousFile, wasManaged := before.managedFile(jsManifestFilename)
	previous, err := decodeJSProperties(previousFile.Properties, "entrypoint")
	if err != nil {
		return nil, nil, fmt.Errorf("decode %s ownership: %w", jsManifestFilename, err)
	}
	source, exists := current[jsManifestFilename]
	actual := map[string]string{}
	if exists && len(bytes.TrimSpace(source)) != 0 {
		manifest, err := jsservice.ParseManifest(source)
		if err != nil {
			return nil, nil, fmt.Errorf("parse %s: %w", jsManifestFilename, err)
		}
		for _, entrypoint := range manifest.Entrypoints {
			actual[entrypoint.Name] = entrypoint.Module
		}
	}
	records, err := reconcileJSProperties("entrypoint", actual, previous, desired)
	if err != nil {
		return nil, nil, fmt.Errorf("%s: %w", jsManifestFilename, err)
	}
	document, err := tomlcode.Parse(source)
	if err != nil {
		return nil, nil, fmt.Errorf("parse %s for edit: %w", jsManifestFilename, err)
	}
	keys := make([]string, 0, len(records.changes))
	for key := range records.changes {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		table := "entrypoint." + key
		value := records.changes[key]
		if value == nil {
			// Removing only module would leave an invalid entrypoint, while
			// removing the whole table would delete application-owned keys.
			// Stop the transaction so the application can take ownership of
			// the entrypoint and its package dependency explicitly.
			if tomlTableHasOtherKeys(source, table, "module") {
				return nil, nil, fmt.Errorf("%s entrypoint %q has application-owned keys; remove them or take ownership before removing the add-on", jsManifestFilename, key)
			}
			if _, err := document.RemoveTable(table); err != nil {
				return nil, nil, fmt.Errorf("remove %s %s: %w", jsManifestFilename, table, err)
			}
			continue
		}
		if _, err := document.EnsureTable(table); err != nil {
			return nil, nil, fmt.Errorf("ensure %s %s: %w", jsManifestFilename, table, err)
		}
		if _, err := document.SetString(table, "module", *value); err != nil {
			return nil, nil, fmt.Errorf("set %s %s.module: %w", jsManifestFilename, table, err)
		}
	}
	data := document.Bytes()
	remove := len(records.properties) == 0 && wasManaged && previousFile.Kind == "js-created" && len(bytes.TrimSpace(data)) == 0
	var operation lazycode.Operation
	if remove {
		operation = lazycode.OperationFunc(func(workspace *lazycode.Workspace) error { return workspace.Remove(jsManifestFilename) })
	} else if len(records.properties) != 0 || wasManaged {
		if !exists || !bytes.Equal(source, data) {
			output := append([]byte(nil), data...)
			operation = lazycode.OperationFunc(func(workspace *lazycode.Workspace) error {
				return workspace.Replace(jsManifestFilename, output)
			})
		}
	}
	if len(records.properties) == 0 {
		return operation, nil, nil
	}
	kind := "js-rewrite"
	if wasManaged {
		kind = previousFile.Kind
	} else if !exists {
		kind = "js-created"
	}
	file := &ManagedFile{Path: jsManifestFilename, Kind: kind, Owners: records.owners, Mode: 0o644, Properties: encodeJSProperties(records.properties)}
	return operation, file, nil
}

func tomlTableHasOtherKeys(source []byte, table, ownedKey string) bool {
	section := ""
	for _, rawLine := range strings.Split(string(source), "\n") {
		line := strings.TrimSpace(stripComment(rawLine))
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			section = strings.TrimSpace(strings.Trim(line, "[]"))
			continue
		}
		if section != table || line == "" {
			continue
		}
		key, _, ok := strings.Cut(line, "=")
		if ok && strings.TrimSpace(key) != ownedKey {
			return true
		}
	}
	return false
}

type propertyReconciliation struct {
	properties []jsProperty
	changes    map[string]*string
	owners     []string
}

func reconcileJSProperties(kind string, actual map[string]string, previous map[string]jsProperty, desired map[string]desiredProperty) (propertyReconciliation, error) {
	result := propertyReconciliation{changes: map[string]*string{}}
	for key, record := range previous {
		value, exists := actual[key]
		if !exists || value != record.Expected {
			return propertyReconciliation{}, fmt.Errorf("managed %s %q drifted from %q", kind, key, record.Expected)
		}
	}
	keys := map[string]bool{}
	for key := range previous {
		keys[key] = true
	}
	for key := range desired {
		keys[key] = true
	}
	ordered := make([]string, 0, len(keys))
	for key := range keys {
		ordered = append(ordered, key)
	}
	sort.Strings(ordered)
	for _, key := range ordered {
		want, wanted := desired[key]
		old, tracked := previous[key]
		if wanted {
			if !tracked {
				if value, exists := actual[key]; exists && value != want.value {
					return propertyReconciliation{}, fmt.Errorf("%s %q already has incompatible value %q", kind, key, value)
				}
				if value, exists := actual[key]; exists {
					old.Previous = stringPointer(value)
				}
			}
			old.Kind = kind
			old.Key = key
			old.Expected = want.value
			old.Owners = normalizedStrings(want.owners)
			value := want.value
			result.changes[key] = &value
			result.properties = append(result.properties, old)
			result.owners = append(result.owners, old.Owners...)
			continue
		}
		if old.Previous == nil {
			result.changes[key] = nil
		} else {
			value := *old.Previous
			result.changes[key] = &value
		}
	}
	result.owners = normalizedStrings(result.owners)
	return result, nil
}

func encodeJSProperties(properties []jsProperty) []string {
	encoded := make([]string, 0, len(properties))
	for _, property := range properties {
		property.Owners = normalizedStrings(property.Owners)
		data, _ := json.Marshal(property)
		encoded = append(encoded, jsPropertyPrefix+string(data))
	}
	sort.Strings(encoded)
	return encoded
}

func decodeJSProperties(values []string, kind string) (map[string]jsProperty, error) {
	properties := map[string]jsProperty{}
	for _, value := range values {
		if !strings.HasPrefix(value, jsPropertyPrefix) {
			continue
		}
		var property jsProperty
		if err := json.Unmarshal([]byte(strings.TrimPrefix(value, jsPropertyPrefix)), &property); err != nil {
			return nil, err
		}
		if property.Kind != kind || property.Key == "" || property.Expected == "" || len(property.Owners) == 0 {
			return nil, fmt.Errorf("invalid %s property record %q", kind, value)
		}
		if _, duplicate := properties[property.Key]; duplicate {
			return nil, fmt.Errorf("duplicate %s property %q", kind, property.Key)
		}
		properties[property.Key] = property
	}
	return properties, nil
}

func stringPointer(value string) *string {
	copy := value
	return &copy
}
